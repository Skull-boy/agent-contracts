"""Generate schema-valid v1.1 contract drafts from an audit report.

Implements RFC 0004 §5 (contract draft generation) and §10.1 (a draft marks a
side effect irreversible only for critical findings). The audit engine scans,
:mod:`scyvera.report` formats, and this module drafts.

:func:`build_draft` is pure: it reads an :class:`~scyvera.audit.AuditReport`
and returns a mapping. :func:`write_draft` is the only side effectful public
function and writes exactly one YAML file, as pinned by RFC 0004 §9.

Draft content is merged from every scored finding's ``suggestion`` fragments.
Quarantined findings (``scored: false``) contribute nothing: a fixture is not
repository behavior.
"""
from __future__ import annotations

from collections.abc import Iterable, Mapping, Sequence
import json
from pathlib import Path
import re
from types import MappingProxyType
from typing import Any

import yaml

from .audit import AuditReport
from .audit_rules import Finding
from .packs import PolicyPack


__all__ = ["DraftContract", "build_draft", "write_draft"]


_RISK_BY_SEVERITY: Mapping[str, str] = MappingProxyType(
    {
        "critical": "critical",
        "high": "high",
        "medium": "medium",
        "low": "low",
    }
)
_SEVERITY_RANK: Mapping[str, int] = MappingProxyType(
    {
        "critical": 0,
        "high": 1,
        "medium": 2,
        "low": 3,
    }
)
_OBSERVABILITY_RANK: Mapping[str, int] = MappingProxyType(
    {
        "none": 0,
        "basic": 1,
        "audit": 2,
        "verbose": 3,
    }
)

_LIST_SECTIONS = frozenset(
    {"capabilities", "resources", "permissions", "side_effects", "approvals"}
)
_ENTRY_ORDER: Mapping[str, tuple[str, ...]] = MappingProxyType(
    {
        "capabilities": ("name", "description"),
        "resources": ("name", "type", "access", "resource", "scope"),
        "side_effects": ("type", "resource", "description", "irreversible"),
        "approvals": ("action", "required", "approver", "condition"),
    }
)
_SORT_FIELDS: Mapping[str, tuple[str, ...]] = MappingProxyType(
    {
        "capabilities": ("name", "description"),
        "resources": ("name", "type", "access"),
        "side_effects": ("type", "resource", "description"),
        "approvals": ("action", "required"),
    }
)

_HEADER_LINES: tuple[str, ...] = (
    "# Contract draft generated by `scyvera audit`.",
    "# Review the inferred permissions, side effects, and approvals before adopting.",
    "#   scyvera validate <this file> && scyvera lint <this file>",
)


class DraftContract(dict[str, Any]):
    """A generated v1.1 draft plus non-serialized provenance metadata.

    ``omitted_suggestion_keys`` records suggestion keys that no v1.1 section
    could represent, so :func:`write_draft` can mention them in the header
    instead of dropping them silently (RFC 0004 §5).
    """

    def __init__(
        self,
        body: Mapping[str, Any] | None = None,
        *,
        omitted_suggestion_keys: Iterable[str] = (),
    ) -> None:
        super().__init__(body or {})
        self.omitted_suggestion_keys = tuple(
            sorted(set(omitted_suggestion_keys))
        )


def _canonical(value: Any) -> str:
    """Return a stable structural key used for deduplication and sorting."""
    return json.dumps(
        value,
        sort_keys=True,
        ensure_ascii=False,
        separators=(",", ":"),
    )


def _ordered_entry(
    entry: Mapping[str, Any],
    preferred: Sequence[str],
) -> dict[str, Any]:
    """Return ``entry`` with known keys first and unknown keys sorted after."""
    ordered: dict[str, Any] = {}
    for key in preferred:
        if key in entry:
            ordered[key] = entry[key]
    for key in sorted(key for key in entry if key not in ordered):
        ordered[key] = entry[key]
    return ordered


def _target_name(target: str) -> str:
    """Return the scanned target's directory name, falling back to ``cwd``."""
    name = Path(target).name
    if name in {"", ".", ".."}:
        return Path.cwd().name
    return name


def _contract_name(report: AuditReport, repo_name: str | None) -> str:
    """Return a lowercase, dash-separated contract name (RFC 0004 §5).

    The name comes from ``repo_name`` when supplied, otherwise from the
    scanned target's basename. Every run of non-ASCII-alphanumeric characters
    collapses to one dash; an empty result falls back to
    ``generated-system`` so the schema's ``minLength: 1`` always holds.
    """
    raw = repo_name if repo_name is not None else _target_name(report.target)
    slug = re.sub(r"[^a-z0-9]+", "-", raw.strip().lower()).strip("-")
    return slug or "generated-system"


def _risk_level(findings: Sequence[Finding]) -> str:
    """Map the worst scored severity onto the v1.1 ``risk.level`` enum."""
    if not findings:
        return "low"
    worst = min(
        findings,
        key=lambda finding: _SEVERITY_RANK.get(
            finding.severity,
            len(_SEVERITY_RANK),
        ),
    )
    return _RISK_BY_SEVERITY.get(worst.severity, "low")


def _normalize_side_effect(entry: Any, severity: str) -> Any:
    """Enforce RFC 0004 §10.1 at the fragment level.

    Critical findings graft ``irreversible: true`` even when the rule omitted
    it. Every other severity drops the flag, so a medium/high finding can
    never make a draft irreversible.
    """
    if not isinstance(entry, Mapping):
        return entry
    normalized = dict(entry)
    if severity == "critical":
        normalized["irreversible"] = True
    else:
        normalized.pop("irreversible", None)
    return normalized


def _merge_observability(
    current: dict[str, Any] | None,
    value: Mapping[str, Any],
) -> dict[str, Any]:
    """Merge one observability fragment, keeping the highest level."""
    result = dict(current or {})
    level = value.get("level")
    if isinstance(level, str):
        existing = result.get("level")
        if (
            not isinstance(existing, str)
            or _OBSERVABILITY_RANK.get(level, 0)
            > _OBSERVABILITY_RANK.get(existing, 0)
        ):
            result["level"] = level

    sinks = value.get("sinks")
    if isinstance(sinks, list):
        merged = set(result.get("sinks", ()))
        merged.update(item for item in sinks if isinstance(item, str))
        result["sinks"] = sorted(merged)
    return result


def _dedupe(items: Iterable[Any], section: str) -> list[Any]:
    """Collapse structurally identical entries and sort deterministically."""
    unique: dict[str, Any] = {}
    for item in items:
        if isinstance(item, Mapping) and section in _ENTRY_ORDER:
            item = _ordered_entry(item, _ENTRY_ORDER[section])
        unique.setdefault(_canonical(item), item)

    if section == "permissions":
        return sorted(
            unique.values(),
            key=lambda item: (
                (0, item)
                if isinstance(item, str)
                else (1, _canonical(item))
            ),
        )

    fields = _SORT_FIELDS.get(section, ())
    return sorted(
        unique.values(),
        key=lambda item: _sort_key(item, fields),
    )


def _sort_key(item: Any, fields: Sequence[str]) -> tuple[str, ...]:
    """Return a homogeneous, deterministic sort key for one merged entry."""
    if isinstance(item, Mapping):
        return tuple(str(item.get(field, "")) for field in fields) + (
            _canonical(item),
        )
    return (str(item),)


def _dedupe_side_effects(items: Iterable[Any]) -> list[Any]:
    """Collapse side effects by type/resource/description, keeping criticality.

    A critical finding wins over a non-critical duplicate, so an effect that
    both severities justify stays irreversible (RFC 0004 §10.1).
    """
    merged: dict[tuple[str, str, str], dict[str, Any]] = {}
    others: dict[str, Any] = {}

    for item in items:
        if isinstance(item, Mapping):
            key = (
                str(item.get("type", "")),
                str(item.get("resource", "")),
                str(item.get("description", "")),
            )
            existing = merged.get(key)
            if existing is None:
                merged[key] = _ordered_entry(
                    item,
                    _ENTRY_ORDER["side_effects"],
                )
            elif item.get("irreversible") is True:
                existing["irreversible"] = True
        else:
            others.setdefault(_canonical(item), item)

    combined: list[Any] = [*merged.values(), *others.values()]
    return sorted(
        combined,
        key=lambda item: _sort_key(item, _SORT_FIELDS["side_effects"]),
    )


def _merge_suggestions(
    findings: Sequence[Finding],
) -> tuple[dict[str, Any], tuple[str, ...]]:
    """Merge suggestion fragments into draft sections (RFC 0004 §5).

    Unknown suggestion keys are omitted and returned as a sorted tuple so the
    writer can list them in the header. A known section carrying a non-list
    value is treated the same way: omitted and reported, never guessed at.
    """
    collected: dict[str, list[Any]] = {
        section: [] for section in _LIST_SECTIONS
    }
    observability: dict[str, Any] | None = None
    omitted: set[str] = set()

    for finding in findings:
        for key, value in finding.suggestion.items():
            if key in _LIST_SECTIONS:
                if not isinstance(value, list):
                    omitted.add(key)
                    continue
                for entry in value:
                    if key == "side_effects":
                        entry = _normalize_side_effect(
                            entry,
                            finding.severity,
                        )
                    collected[key].append(entry)
            elif key == "observability":
                if isinstance(value, Mapping):
                    observability = _merge_observability(
                        observability,
                        value,
                    )
                else:
                    omitted.add(key)
            else:
                omitted.add(key)

    merged: dict[str, Any] = {}
    for section in ("capabilities", "resources", "permissions", "approvals"):
        merged[section] = _dedupe(collected[section], section)
    merged["side_effects"] = _dedupe_side_effects(
        collected["side_effects"]
    )
    merged["observability"] = observability
    return merged, tuple(sorted(omitted))


def _approval_action(entry: Any) -> str | None:
    """Return the action named by one approval entry, if any."""
    if isinstance(entry, str):
        return entry
    if isinstance(entry, Mapping):
        action = entry.get("action")
        if isinstance(action, str):
            return action
    return None


def _ensure_approvals(
    approvals: list[Any],
    side_effects: list[Any],
    risk_level: str,
) -> list[Any]:
    """Guarantee approval boundaries for the draft's risk level.

    Every irreversible side effect gains an approval boundary (AC302). A
    high/critical draft with no approvals at all gains one per side-effect
    type, or a final ``manual_review`` boundary, so it never ships with
    lint warnings.
    """
    result: list[Any] = list(approvals)
    actions = {
        action
        for entry in result
        if (action := _approval_action(entry)) is not None
    }

    def add(action: str) -> None:
        if action in actions:
            return
        result.append({"action": action, "required": True})
        actions.add(action)

    for effect in side_effects:
        if (
            isinstance(effect, Mapping)
            and effect.get("irreversible") is True
        ):
            effect_type = effect.get("type")
            if isinstance(effect_type, str) and effect_type:
                add(effect_type)

    if risk_level in {"high", "critical"} and not result:
        for effect in side_effects:
            if isinstance(effect, Mapping):
                effect_type = effect.get("type")
                if isinstance(effect_type, str) and effect_type:
                    add(effect_type)
        if not result:
            add("manual_review")

    return _dedupe(result, "approvals")


def _normalize_observability(
    observability: dict[str, Any] | None,
    side_effects: list[Any],
) -> dict[str, Any]:
    """Return a schema-valid observability object (AC601 safe)."""
    result = dict(observability) if observability else {}
    if not isinstance(result.get("level"), str):
        result["level"] = "basic"
    if side_effects and result["level"] == "none":
        result["level"] = "basic"

    sinks = result.get("sinks")
    if isinstance(sinks, list):
        result["sinks"] = sorted(
            {item for item in sinks if isinstance(item, str)}
        )
    return _ordered_entry(result, ("level", "sinks"))


def _apply_pack(body: dict[str, Any], pack: PolicyPack) -> None:
    """Apply pack constraints to ``body`` in place (RFC 0004 §6).

    Pack constraints win over heuristic-derived entries: a forbidden side
    effect becomes irreversible and loses every approval entry (the RFC pins
    "no approvals offered"); a required action gains a required approval.
    Entries the pack does not mention are finding-only extras and are kept.

    ``construction.cap_side_effects_per_window`` maps to the v1.1
    ``constraints`` section, whose schema already models a numeric limit with
    ``type`` and ``maximum``. The constraint type mirrors the field name used
    by the v1.2 guardrail projection in RFC 0003 §C5.
    """
    forbidden = set(pack.irreversibly_forbidden)
    required = set(pack.requires_approval)

    effects: list[Any] = []
    present: set[str] = set()
    for entry in body["side_effects"]:
        if isinstance(entry, Mapping):
            effect_type = entry.get("type")
            if isinstance(effect_type, str):
                present.add(effect_type)
                if effect_type in forbidden:
                    entry = dict(entry)
                    entry["irreversible"] = True
        effects.append(entry)
    for effect_type in sorted(forbidden - present):
        effects.append({"type": effect_type, "irreversible": True})
    body["side_effects"] = _dedupe_side_effects(effects)

    approvals: list[Any] = []
    required_seen: set[str] = set()
    for entry in body["approvals"]:
        action = _approval_action(entry)
        if action is None:
            approvals.append(entry)
            continue
        if action in forbidden:
            continue
        if action in required:
            entry = (
                dict(entry)
                if isinstance(entry, Mapping)
                else {"action": entry}
            )
            entry["required"] = True
            required_seen.add(action)
        approvals.append(entry)
    for action in sorted(required - required_seen):
        approvals.append({"action": action, "required": True})
    body["approvals"] = _dedupe(approvals, "approvals")

    if pack.cap_side_effects_per_window is not None:
        constraint = {
            "type": "side_effects_per_window",
            "maximum": pack.cap_side_effects_per_window,
        }
        constraints = [
            entry
            for entry in body.get("constraints", [])
            if not (
                isinstance(entry, Mapping)
                and entry.get("type") == "side_effects_per_window"
            )
        ]
        constraints.append(constraint)
        body["constraints"] = sorted(
            constraints,
            key=lambda entry: _sort_key(entry, ("type", "maximum")),
        )


def build_draft(
    report: AuditReport,
    *,
    repo_name: str | None = None,
    domain: str = "software",
    pack: PolicyPack | None = None,
) -> DraftContract:
    """Build a v1.1 contract draft from ``report`` (RFC 0004 §5, §6).

    Only scored findings contribute. ``repo_name`` overrides the name derived
    from the scanned target; ``domain`` defaults to ``"software"`` as pinned
    by the RFC. When ``pack`` is supplied, its domain replaces ``domain`` and
    its ``derive.*`` constraints are merged into the draft (RFC 0004 §5–§6).
    The returned mapping preserves the field order used by ``scyvera init``
    and carries any omitted suggestion keys as metadata for
    :func:`write_draft`.
    """
    scored = tuple(finding for finding in report.findings if finding.scored)
    risk_level = _risk_level(scored)
    merged, omitted = _merge_suggestions(scored)
    if pack is not None:
        domain = pack.domain

    side_effects = merged["side_effects"]
    approvals = _ensure_approvals(
        merged["approvals"],
        side_effects,
        risk_level,
    )
    observability = _normalize_observability(
        merged["observability"],
        side_effects,
    )

    body: dict[str, Any] = {
        "version": 1.1,
        "system": {
            "name": _contract_name(report, repo_name),
            "purpose": (
                "Contract draft inferred from a Scyvera audit report; "
                "review before adoption."
            ),
            "version": "1.0.0",
        },
        "domain": domain,
        "capabilities": merged["capabilities"],
        "resources": merged["resources"],
        "inputs": [],
        "outputs": [],
        "permissions": merged["permissions"],
    }
    if pack is not None and pack.cap_side_effects_per_window is not None:
        body["constraints"] = [
            {
                "type": "side_effects_per_window",
                "maximum": pack.cap_side_effects_per_window,
            }
        ]
    body.update(
        {
            "side_effects": side_effects,
            "approvals": approvals,
            "dependencies": [],
            "state": {"persistence": "session"},
            "recovery": {"strategy": "retry"},
            "replay": {"mode": "idempotent"},
            "observability": observability,
            "risk": {"level": risk_level},
        }
    )
    if pack is not None:
        _apply_pack(body, pack)
    return DraftContract(body, omitted_suggestion_keys=omitted)


def write_draft(draft: Mapping[str, Any], path: str | Path) -> None:
    """Write ``draft`` to ``path`` as deterministic, ASCII-only YAML.

    Implements RFC 0004 §5 and §9: exactly one file is written, with a
    plain-language adoption header. Key order comes from the mapping (never
    hash order), values that YAML would treat specially are quoted by the
    emitter, and non-ASCII values are escaped so the file is safe to read on
    a cp850 console and as UTF-8. No timestamps, backups, or side-car files
    are produced.
    """
    output_path = Path(path)
    output_path.parent.mkdir(parents=True, exist_ok=True)

    body = yaml.safe_dump(
        dict(draft),
        sort_keys=False,
        default_flow_style=False,
        allow_unicode=False,
        width=88,
    )

    header = list(_HEADER_LINES)
    omitted = getattr(draft, "omitted_suggestion_keys", ())
    if omitted:
        header.append(
            "# Omitted unsupported suggestion keys: "
            + ", ".join(omitted)
            + "."
        )

    payload = "\n".join(header) + "\n" + body
    payload = payload.encode("ascii", "backslashreplace").decode("ascii")

    with output_path.open("w", encoding="ascii", newline="\n") as handle:
        handle.write(payload)
