"""Package self-integrity for the installed ``scyvera`` distribution.

RFC 0003 §C2 ("Package Self-Integrity") extends the T5 file-replacement
guarantee from the *contract* layer to the *enforcer itself*: a signed
manifest lists ``{path, sha256}`` for every runtime-critical file, and
``scyvera self-check`` verifies the installed distribution against it, failing
closed on any mismatch. Roadmap task M3.4 ships the verifier; the manifest is
generated by :mod:`tools.generate_self_manifest` and bound into the signed
release bundle from RFC 0003 §C6 / roadmap M3.3, which is the T11 mitigation.

The manifest format is deliberately small and timestamp-free::

    {
      "manifest_version": "1",
      "name": "scyvera",
      "version": "<package version>",
      "files": [{"path": "...", "sha256": "..."}]
    }

Paths are package-root relative, POSIX-separated, and sorted
lexicographically, so generation is byte-deterministic. Provenance time lives
in the release attestation (RFC 0003 §C6), never in the manifest.

Fail-closed rules:

- A manifest-listed file that is missing or has a different SHA-256 fails.
- A file under the package root that is *not* listed and *not* excluded fails.
  Additions are a tampering surface, for example a dropped-in module override
  (T5-consistent).
- A missing, malformed, or unsupported manifest fails closed with an
  actionable message; the CLI maps that "unverifiable" case to exit code 2.
- Manifest paths must be relative POSIX paths with no ``..`` component, so a
  hostile manifest cannot redirect verification outside the package.

The engine is pure: it never prints, never logs, and never writes to the tree.
It resolves the installed package through :mod:`importlib.resources` (never the
current working directory) unless a caller explicitly passes a package path
for tests or release tooling.
"""

from __future__ import annotations

from dataclasses import dataclass
import hashlib
import importlib.metadata
import importlib.resources
import json
from pathlib import Path, PurePosixPath
import re
from typing import Any, Optional, Sequence

__all__ = [
    "CHECK_MODIFIED",
    "CHECK_MISSING",
    "CHECK_OK",
    "CHECK_UNLISTED",
    "DEFAULT_EXCLUSIONS",
    "FAILURE_MANIFEST_INVALID",
    "FAILURE_MANIFEST_MISSING",
    "FAILURE_MANIFEST_VERSION_MISMATCH",
    "FAILURE_MISSING",
    "FAILURE_MODIFIED",
    "FAILURE_UNLISTED",
    "FAILURE_VERSION_MISMATCH",
    "SELF_CHECK_REPORT_VERSION",
    "SELF_MANIFEST_FILENAME",
    "SELF_MANIFEST_NAME",
    "SELF_MANIFEST_VERSION",
    "SelfCheckEntry",
    "SelfCheckError",
    "SelfCheckFailure",
    "SelfCheckResult",
    "generate_manifest",
    "self_check",
]

#: RFC 0003 §C2 manifest schema version shipped by this release.
SELF_MANIFEST_VERSION: str = "1"

#: Packaged manifest filename (included as package data in ``pyproject.toml``).
SELF_MANIFEST_FILENAME: str = "_self_manifest.json"

#: Distribution name the manifest describes.
SELF_MANIFEST_NAME: str = "scyvera"

#: Version of the machine-readable self-check report.
SELF_CHECK_REPORT_VERSION: int = 1

#: Per-entry verification status values.
CHECK_OK: str = "ok"
CHECK_MODIFIED: str = "modified"
CHECK_MISSING: str = "missing"
CHECK_UNLISTED: str = "unlisted"

#: Failure codes surfaced in :attr:`SelfCheckResult.failures`.
FAILURE_MANIFEST_MISSING: str = "manifest-missing"
FAILURE_MANIFEST_INVALID: str = "manifest-invalid"
FAILURE_MANIFEST_VERSION_MISMATCH: str = "manifest-version-mismatch"
FAILURE_VERSION_MISMATCH: str = "version-mismatch"
FAILURE_MODIFIED: str = "modified"
FAILURE_MISSING: str = "missing"
FAILURE_UNLISTED: str = "unlisted"

#: Build/VCS artefacts that are not part of the installed runtime surface.
#:
#: ``_self_manifest.json`` itself is reserved because it cannot hash itself;
#: the exclusion is exact, not a wildcard, so a different JSON file under the
#: package root is still treated as an unlisted addition.
DEFAULT_EXCLUSIONS: tuple[str, ...] = (
    "__pycache__/",
    "*.pyc",
    "*.pyo",
    ".git*",
    "*.egg-info/",
    "*.dist-info/",
    SELF_MANIFEST_FILENAME,
)

_VERSION_PATTERN = re.compile(
    r'^__version__\s*=\s*["\']([^"\']+)["\']',
    re.MULTILINE,
)
_READ_CHUNK_BYTES = 64 * 1024


class SelfCheckError(Exception):
    """Raised when self-check cannot run at all (missing install, bad input).

    Integrity deviations are reported as :class:`SelfCheckFailure` values, not
    exceptions, so callers can enumerate every problem. This error is reserved
    for conditions that make verification meaningless: the installed
    distribution cannot be located, the package root is not a directory, or a
    supplied path is unusable.
    """

    def __init__(self, operation: str, reason: str) -> None:
        self.operation = operation
        self.reason = reason
        super().__init__(f"Self-check error during '{operation}': {reason}")


@dataclass(frozen=True)
class SelfCheckEntry:
    """One verified (or deviating) file in deterministic path order."""

    path: str
    expected_sha256: Optional[str]
    actual_sha256: Optional[str]
    status: str


@dataclass(frozen=True)
class SelfCheckFailure:
    """One actionable self-check failure.

    ``path`` is the package-root-relative POSIX path for file deviations and
    ``None`` for manifest-level failures (missing/invalid/version mismatch).
    """

    code: str
    path: Optional[str]
    message: str


@dataclass(frozen=True)
class SelfCheckResult:
    """Frozen result of one :func:`self_check` run.

    ``entries`` covers every manifest-listed file plus every unlisted addition;
    ``failures`` is the fail-closed subset. ``passed`` is exactly
    ``not failures``. ``manifest_version`` is ``None`` when the manifest is
    missing or unreadable, and ``package_version`` is the installed
    distribution version where one could be determined.
    """

    entries: Sequence[SelfCheckEntry]
    passed: bool
    failures: Sequence[SelfCheckFailure]
    manifest_version: Optional[str]
    package_version: Optional[str]

    def to_dict(self) -> dict[str, Any]:
        """Return the machine-readable report as JSON-serializable data."""
        return {
            "self_check_version": SELF_CHECK_REPORT_VERSION,
            "manifest_version": self.manifest_version,
            "package_version": self.package_version,
            "passed": self.passed,
            "entries": [
                {
                    "path": entry.path,
                    "expected_sha256": entry.expected_sha256,
                    "actual_sha256": entry.actual_sha256,
                    "status": entry.status,
                }
                for entry in self.entries
            ],
            "failures": [
                {
                    "code": failure.code,
                    "path": failure.path,
                    "message": failure.message,
                }
                for failure in self.failures
            ],
        }

    def to_json(self) -> str:
        """Serialize with the same conventions as the audit report."""
        return json.dumps(self.to_dict(), indent=2, ensure_ascii=False)


def _sha256_file(path: Path) -> str:
    """Return the SHA-256 hex digest of ``path`` without loading it whole."""
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(_READ_CHUNK_BYTES), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _is_excluded(relative_path: str) -> bool:
    """Return whether a package-relative POSIX path is build/VCS noise.

    The rules mirror :data:`DEFAULT_EXCLUSIONS` exactly. ``.git*`` and
    ``*.egg-info``/``*.dist-info`` match any path component, so metadata
    directories are excluded wherever a tool puts them under the package root.
    """
    parts = PurePosixPath(relative_path).parts
    if not parts:
        return True

    for part in parts:
        if part == "__pycache__":
            return True
        if part.startswith(".git"):
            return True
        if part.endswith(".egg-info") or part.endswith(".dist-info"):
            return True

    name = parts[-1]
    if name == SELF_MANIFEST_FILENAME:
        return True
    if name.endswith(".pyc") or name.endswith(".pyo"):
        return True
    return False


def _iter_package_files(package_path: Path) -> list[str]:
    """Return sorted package-relative POSIX paths for manifestable files."""
    files: list[str] = []
    for candidate in package_path.rglob("*"):
        if not candidate.is_file():
            continue
        relative = candidate.relative_to(package_path).as_posix()
        if _is_excluded(relative):
            continue
        files.append(relative)
    return sorted(files)


def _version_from_tree(package_path: Path) -> str:
    """Read ``__version__`` from the package's ``__init__.py`` without import.

    Importing the package to discover its version would execute arbitrary code
    and make manifest generation order-dependent. The installed distribution
    version is the fallback for unusual layouts.
    """
    init_path = package_path / "__init__.py"
    if init_path.is_file():
        try:
            source = init_path.read_text(encoding="utf-8")
        except OSError as exc:
            raise SelfCheckError(
                "version",
                f"cannot read '{init_path}': {exc}",
            ) from exc
        match = _VERSION_PATTERN.search(source)
        if match is not None:
            return match.group(1)

    try:
        return importlib.metadata.version(SELF_MANIFEST_NAME)
    except importlib.metadata.PackageNotFoundError as exc:
        raise SelfCheckError(
            "version",
            "cannot determine the package version from "
            f"'{init_path}' or installed distribution metadata",
        ) from exc


def _installed_version() -> str:
    """Return the installed ``scyvera`` distribution version (fail closed)."""
    try:
        return importlib.metadata.version(SELF_MANIFEST_NAME)
    except importlib.metadata.PackageNotFoundError as exc:
        raise SelfCheckError(
            "version",
            "the scyvera distribution is not installed; "
            "self-check verifies an installed distribution, not a source "
            "checkout",
        ) from exc


def _resolve_package_root(package_path: Optional[Path]) -> Path:
    """Resolve the package root to verify.

    With no argument, resolution goes through :mod:`importlib.resources` so the
    CLI can never accidentally verify the current working directory. An
    explicit path is used verbatim by tests and release tooling.
    """
    if package_path is not None:
        root = Path(package_path)
        if not root.is_dir():
            raise SelfCheckError(
                "package-path",
                f"package directory not found: '{root}'",
            )
        return root

    try:
        resource = importlib.resources.files(SELF_MANIFEST_NAME)
    except (ModuleNotFoundError, TypeError) as exc:
        raise SelfCheckError(
            "package-path",
            "cannot resolve the installed scyvera package via "
            f"importlib.resources: {exc}",
        ) from exc

    root = Path(str(resource))
    if not root.is_dir():
        raise SelfCheckError(
            "package-path",
            "the installed scyvera package is not a filesystem directory "
            f"('{root}'); self-check requires an unpacked wheel install",
        )
    return root


def generate_manifest(package_path: Path) -> bytes:
    """Return canonical manifest bytes for the tree at ``package_path``.

    The walk includes every regular file under the package root except
    :data:`DEFAULT_EXCLUSIONS`, so a dropped-in addition is later caught by
    :func:`self_check`. Files are hashed with SHA-256, paths are POSIX and
    lexicographically sorted, and JSON uses ``sort_keys`` with compact
    separators. No timestamp is included: repeated generation over the same
    tree is byte-identical.

    Args:
        package_path: Directory containing the ``scyvera`` package files.

    Returns:
        Canonical UTF-8 JSON manifest bytes.

    Raises:
        SelfCheckError: If ``package_path`` is not a directory or the version
            cannot be determined.
    """
    root = Path(package_path)
    if not root.is_dir():
        raise SelfCheckError(
            "manifest",
            f"package directory not found: '{root}'",
        )

    version = _version_from_tree(root)
    files = [
        {"path": relative, "sha256": _sha256_file(root / relative)}
        for relative in _iter_package_files(root)
    ]
    payload: dict[str, Any] = {
        "manifest_version": SELF_MANIFEST_VERSION,
        "name": SELF_MANIFEST_NAME,
        "version": version,
        "files": files,
    }
    return json.dumps(
        payload,
        sort_keys=True,
        separators=(",", ":"),
        ensure_ascii=False,
    ).encode("utf-8")


def _safe_relative_path(value: str) -> bool:
    """Return whether ``value`` is a safe package-relative POSIX path."""
    if not value or value.startswith("/") or "\\" in value:
        return False
    return all(part not in {"", ".", ".."} for part in value.split("/"))


def _failure(code: str, path: Optional[str], message: str) -> SelfCheckFailure:
    return SelfCheckFailure(code=code, path=path, message=message)


def _manifest_failure(
    code: str,
    message: str,
    *,
    package_version: Optional[str],
    manifest_version: Optional[str] = None,
) -> SelfCheckResult:
    return SelfCheckResult(
        entries=(),
        passed=False,
        failures=(_failure(code, None, message),),
        manifest_version=manifest_version,
        package_version=package_version,
    )


def _parse_manifest(
    raw: Any,
    *,
    package_version: str,
) -> tuple[str, str, list[tuple[str, str]], list[SelfCheckFailure]]:
    """Validate manifest structure and return schema version, files, failures.

    Raises:
        SelfCheckError: On structural problems that make file verification
            meaningless (the caller turns this into ``manifest-invalid``).
    """
    if not isinstance(raw, dict):
        raise SelfCheckError("manifest", "manifest root must be a JSON object")

    manifest_version = raw.get("manifest_version")
    if manifest_version != SELF_MANIFEST_VERSION:
        raise _UnsupportedManifestVersion(manifest_version)

    name = raw.get("name")
    if name != SELF_MANIFEST_NAME:
        raise SelfCheckError(
            "manifest",
            f"manifest name must be '{SELF_MANIFEST_NAME}', got {name!r}",
        )

    version = raw.get("version")
    if not isinstance(version, str) or not version:
        raise SelfCheckError("manifest", "manifest 'version' must be a non-empty string")

    files = raw.get("files")
    if not isinstance(files, list):
        raise SelfCheckError("manifest", "manifest 'files' must be a list")

    seen: set[str] = set()
    verified: list[tuple[str, str]] = []
    failures: list[SelfCheckFailure] = []

    if version != package_version:
        failures.append(
            _failure(
                FAILURE_VERSION_MISMATCH,
                None,
                f"manifest version '{version}' does not match installed "
                f"distribution version '{package_version}'",
            )
        )

    for index, item in enumerate(files):
        if not isinstance(item, dict):
            raise SelfCheckError(
                "manifest",
                f"manifest files[{index}] must be a JSON object",
            )
        path = item.get("path")
        digest = item.get("sha256")
        if not isinstance(path, str) or not _safe_relative_path(path):
            raise SelfCheckError(
                "manifest",
                f"manifest files[{index}].path must be a safe relative POSIX path",
            )
        if not isinstance(digest, str) or len(digest) != 64:
            raise SelfCheckError(
                "manifest",
                f"manifest files[{index}].sha256 must be a 64-character hex digest",
            )
        try:
            int(digest, 16)
        except ValueError as exc:
            raise SelfCheckError(
                "manifest",
                f"manifest files[{index}].sha256 is not hexadecimal",
            ) from exc
        if path in seen:
            raise SelfCheckError(
                "manifest",
                f"manifest lists '{path}' more than once",
            )
        seen.add(path)
        verified.append((path, digest.lower()))

    return manifest_version, version, verified, failures


class _UnsupportedManifestVersion(Exception):
    """Internal signal for an unsupported manifest schema version."""

    def __init__(self, value: Any) -> None:
        self.value = value
        super().__init__(str(value))


def self_check(package_path: Optional[Path] = None) -> SelfCheckResult:
    """Verify an installed package tree against its packaged manifest.

    With ``package_path=None`` the *installed* package root is resolved via
    :mod:`importlib.resources`, so running from a source checkout does not
    silently verify the checkout. Tests and release tooling pass an explicit
    package directory.

    The check never raises for integrity deviations: every missing, modified,
    or unlisted file is reported in :attr:`SelfCheckResult.failures`, and
    ``passed`` is false. Manifest-level problems (missing, malformed,
    unsupported schema, name mismatch) are also returned as failures so the
    CLI can present one consistent report.

    Args:
        package_path: Optional package directory to verify instead of the
            installed distribution.

    Returns:
        A frozen :class:`SelfCheckResult`.

    Raises:
        SelfCheckError: If no package root can be resolved, or the installed
            distribution version cannot be determined.
    """
    root = _resolve_package_root(package_path)
    package_version = _installed_version()
    manifest_path = root / SELF_MANIFEST_FILENAME

    if not manifest_path.is_file():
        return _manifest_failure(
            FAILURE_MANIFEST_MISSING,
            (
                f"no self-check manifest at '{manifest_path}'. This install "
                "predates the M3.4 signed manifest or the manifest was "
                "removed. Reinstall scyvera from a signed release; self-check "
                "verifies an installed distribution, not a source checkout."
            ),
            package_version=package_version,
        )

    try:
        raw = json.loads(manifest_path.read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError, json.JSONDecodeError) as exc:
        return _manifest_failure(
            FAILURE_MANIFEST_INVALID,
            f"cannot read self-check manifest '{manifest_path}': {exc}",
            package_version=package_version,
        )

    try:
        (
            manifest_version,
            _manifest_version_of_package,
            listed,
            failures,
        ) = _parse_manifest(raw, package_version=package_version)
    except _UnsupportedManifestVersion as exc:
        return _manifest_failure(
            FAILURE_MANIFEST_VERSION_MISMATCH,
            (
                f"self-check manifest version {exc.value!r} is not supported "
                f"(expected '{SELF_MANIFEST_VERSION}'); upgrade scyvera or "
                "regenerate the manifest with a matching release tool"
            ),
            package_version=package_version,
            manifest_version=(
                exc.value if isinstance(exc.value, str) else None
            ),
        )
    except SelfCheckError as exc:
        return _manifest_failure(
            FAILURE_MANIFEST_INVALID,
            f"invalid self-check manifest '{manifest_path}': {exc.reason}",
            package_version=package_version,
        )

    entries: list[SelfCheckEntry] = []
    failure_list: list[SelfCheckFailure] = list(failures)
    listed_paths = {path for path, _digest in listed}

    for path, expected in listed:
        target = root / PurePosixPath(path)
        if target.is_symlink():
            entries.append(
                SelfCheckEntry(
                    path=path,
                    expected_sha256=expected,
                    actual_sha256=None,
                    status=CHECK_MODIFIED,
                )
            )
            failure_list.append(
                _failure(
                    FAILURE_MODIFIED,
                    path,
                    "listed file is a symlink; self-check requires regular "
                    "files inside the package root",
                )
            )
            continue
        if not target.is_file():
            entries.append(
                SelfCheckEntry(
                    path=path,
                    expected_sha256=expected,
                    actual_sha256=None,
                    status=CHECK_MISSING,
                )
            )
            failure_list.append(
                _failure(
                    FAILURE_MISSING,
                    path,
                    "listed file is missing from the installed package",
                )
            )
            continue

        actual = _sha256_file(target)
        if actual != expected:
            entries.append(
                SelfCheckEntry(
                    path=path,
                    expected_sha256=expected,
                    actual_sha256=actual,
                    status=CHECK_MODIFIED,
                )
            )
            failure_list.append(
                _failure(
                    FAILURE_MODIFIED,
                    path,
                    "SHA-256 does not match the signed manifest",
                )
            )
            continue

        entries.append(
            SelfCheckEntry(
                path=path,
                expected_sha256=expected,
                actual_sha256=actual,
                status=CHECK_OK,
            )
        )

    for path in _iter_package_files(root):
        if path in listed_paths:
            continue
        target = root / PurePosixPath(path)
        actual = _sha256_file(target)
        entries.append(
            SelfCheckEntry(
                path=path,
                expected_sha256=None,
                actual_sha256=actual,
                status=CHECK_UNLISTED,
            )
        )
        failure_list.append(
            _failure(
                FAILURE_UNLISTED,
                path,
                "file is present in the package but absent from the signed "
                "manifest; additions are tampering surface (T5)",
            )
        )

    entries.sort(key=lambda entry: entry.path)
    failure_list.sort(
        key=lambda failure: (
            failure.code,
            failure.path or "",
            failure.message,
        )
    )

    return SelfCheckResult(
        entries=tuple(entries),
        passed=not failure_list,
        failures=tuple(failure_list),
        manifest_version=manifest_version,
        package_version=package_version,
    )
